def path(bmp):
    rows = [r for r in bmp.strip('\n').split('\n')]
    d = []
    for y, row in enumerate(rows):
        for m in re.finditer(r'#+', row):
            d.append(f'M{m.start()} {y}h{m.end() - m.start()}v1h-{m.end() - m.start()}z')
    return ''.join(d)


def sprite():
    out = ['<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">']
    for k, v in ICONS.items():
        out.append(f'<symbol id="i-{k}" viewBox="0 0 16 16"><path d="{path(v)}"/></symbol>')
    out.append('</svg>')
    return ''.join(out)


if __name__ == '__main__':
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    sp = sprite()
    for f in ('index.html', 'note-legali.html', 'privacy.html'):
        p = os.path.join(root, f); s = open(p, encoding='utf-8').read()
        new = re.sub(r'<!-- ICONS -->.*?<!-- /ICONS -->', lambda m: '<!-- ICONS -->' + sp + '<!-- /ICONS -->', s, flags=re.S)
        if new == s and '<!-- ICONS -->' not in s:
            print('no marker in', f); continue
        open(p, 'w', encoding='utf-8', newline='\n').write(new)
    print('icons:', ', '.join(ICONS))
